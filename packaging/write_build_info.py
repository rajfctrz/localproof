"""Stamp build metadata into localproof/_build_info.py before PyInstaller runs.

Honours SOURCE_DATE_EPOCH (reproducible builds) and GITHUB_SHA (CI).
"""

from __future__ import annotations

import os
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "localproof" / "_build_info.py"


def _commit() -> str:
    if os.environ.get("GITHUB_SHA"):
        return os.environ["GITHUB_SHA"]
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _timestamp() -> str:
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    moment = datetime.fromtimestamp(int(epoch), timezone.utc) if epoch else datetime.now(timezone.utc)
    return moment.strftime("%Y-%m-%dT%H:%M:%SZ")


def main() -> None:
    OUT.write_text(
        '"""Generated by packaging/write_build_info.py. Do not edit or commit."""\n\n'
        f'BUILD_TIMESTAMP = "{_timestamp()}"\n'
        f'GIT_COMMIT = "{_commit()}"\n',
        encoding="utf-8",
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
